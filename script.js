let stream=null;
const video=document.getElementById('camera');
document.getElementById('startCamera')?.addEventListener('click',async()=>{
  try{
    stream=await navigator.mediaDevices.getUserMedia({video:true,audio:false});
    video.srcObject=stream;video.hidden=false;document.getElementById('cameraPlaceholder').hidden=true;
    document.getElementById('cameraStatus').textContent='Camera active';
  }catch(err){alert('Camera access was not granted. Allow camera permission in your browser and try again.');}
});
document.getElementById('stopCamera')?.addEventListener('click',()=>{
  stream?.getTracks().forEach(t=>t.stop());stream=null;video.hidden=true;
  document.getElementById('cameraPlaceholder').hidden=false;document.getElementById('cameraStatus').textContent='Camera inactive';
});

