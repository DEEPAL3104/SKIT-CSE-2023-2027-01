const sections = document.querySelectorAll('.page-section');
const navItems = document.querySelectorAll('.nav-item');
const titleMap = {dashboard:'Engagement Dashboard',live:'Live Engagement Analysis',video:'Video Analysis',reports:'Analysis Reports'};
function showSection(id){
  sections.forEach(s=>s.classList.toggle('active-section',s.id===id));
  navItems.forEach(n=>n.classList.toggle('active',n.dataset.section===id));
  document.getElementById('pageTitle').textContent=titleMap[id];
  window.scrollTo({top:0,behavior:'smooth'});
}
navItems.forEach(n=>n.addEventListener('click',()=>showSection(n.dataset.section)));
document.querySelectorAll('[data-goto]').forEach(b=>b.addEventListener('click',()=>showSection(b.dataset.goto)));

const canvas=document.getElementById('trendChart');
const ctx=canvas.getContext('2d');
function drawChart(){
  const dpr=window.devicePixelRatio||1, rect=canvas.getBoundingClientRect();
  canvas.width=rect.width*dpr; canvas.height=rect.height*dpr; ctx.scale(dpr,dpr);
  const w=rect.width,h=rect.height,p=20;
  const data=[61,65,63,70,68,74,72,79,76,82,80,86,82,88,84,82];
  ctx.clearRect(0,0,w,h);
  ctx.strokeStyle='#e9edf3';ctx.lineWidth=1;
  for(let i=0;i<4;i++){const y=p+i*(h-2*p)/3;ctx.beginPath();ctx.moveTo(p,y);ctx.lineTo(w-p,y);ctx.stroke();}
  ctx.beginPath();
  data.forEach((v,i)=>{const x=p+i*(w-2*p)/(data.length-1),y=h-p-(v-50)*(h-2*p)/50;i?ctx.lineTo(x,y):ctx.moveTo(x,y)});
  ctx.strokeStyle='#6278f5';ctx.lineWidth=3;ctx.stroke();
  ctx.lineTo(w-p,h-p);ctx.lineTo(p,h-p);ctx.closePath();
  const g=ctx.createLinearGradient(0,0,0,h);g.addColorStop(0,'rgba(98,120,245,.20)');g.addColorStop(1,'rgba(98,120,245,0)');
  ctx.fillStyle=g;ctx.fill();
}
window.addEventListener('resize',drawChart); drawChart();

